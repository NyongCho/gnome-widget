export type Language='ko'|'en';
export type Message=keyof typeof messages;
export function language(value:string):Language{return value==='en'?'en':'ko';}
export function localeFor(value:Language):string{return value==='en'?'en-US':'ko-KR';}
export function translate(value:Language,message:Message,values:Readonly<Record<string,string|number>>={}):string{
 const template=value==='en'?messages[message]:message;
 return template.replace(/\{(\w+)\}/g,(original,key:string)=>String(values[key]??original));
}
type Binding=Message|(()=>string);
/** Bind only app-owned text properties, leaving input values and async state intact. */
export class TextBindings {
 private targets=new Map<object,Map<PropertyKey,()=>string>>();
 private listeners=new Set<()=>void>();
 language:Language;
 constructor(value:string){this.language=language(value);}
 t(message:Message,values?:Readonly<Record<string,string|number>>):string{return translate(this.language,message,values);}
 bind<T extends object>(target:T,properties:Partial<Record<keyof T,Binding>>):T{
  let bindings=this.targets.get(target);if(!bindings){bindings=new Map();this.targets.set(target,bindings);}
  for(const [property,source] of Object.entries(properties) as [keyof T,Binding][]){
   const read=typeof source==='function'?source:()=>this.t(source);
   bindings.set(property,read);Reflect.set(target,property,read());
  }
  return target;
 }
 onChange(callback:()=>void):void{this.listeners.add(callback);}
 setLanguage(value:string):void{
  this.language=language(value);
  for(const [target,properties] of this.targets)for(const [property,read] of properties)Reflect.set(target,property,read());
  for(const listener of this.listeners)listener();
 }
 unbind(target:object):void{this.targets.delete(target);}
 destroy():void{this.targets.clear();this.listeners.clear();}
}
